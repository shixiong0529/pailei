def to_traditional(text: str) -> str:
    return "".join(S2T_MAP.get(ch, ch) for ch in (text or ""))


def name_variants(name: str) -> list[str]:
    """生成公司简称的字形变体（简/繁），用于原文定位。"""
    base = (name or "").replace("股份有限", "").replace("有限公司", "").strip()
    variants = []
    for candidate in (base, to_traditional(base)):
        if candidate and candidate not in variants:
            variants.append(candidate)
    return variants


RISK_KEYWORDS_A = ["风险", "诉讼", "仲裁", "违规", "处罚", "立案", "冻结", "质押", "担保", "减值"]
RISK_KEYWORDS_HK = [
    "風險", "訴訟", "仲裁", "違規", "處罰", "調查", "凍結", "質押", "擔保", "減值", "虧損", "延遲"
]


def risk_keywords(market: Market) -> list[str]:
    return RISK_KEYWORDS_HK if market is Market.HK else RISK_KEYWORDS_A


def evidence_keywords(name: str, code: str, market: Market) -> list[str]:
    """构造用于定位证据片段的关键词。

    顺序：公司简称（简/繁）→ 证券代码 → 市场风险词。
    证券代码几乎必然出现在定期报告页眉，用作兜底定位。
    """
    keywords = name_variants(name)
    if code:
        keywords.append(code)
    keywords.extend(risk_keywords(market))
    return [k for k in keywords if k]
